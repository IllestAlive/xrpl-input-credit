"""Part D: how much does the ledger tell a lender about default risk?

1. Out-of-time evaluation. A panel is generated by lending equal amounts
   (random order, constant fund each season, so labels do not dry up) for
   6 seasons. For every season t >= 2 a model is trained on seasons < t and
   tested on season t. Feature sets, nested:
     land        log land
     history     + earlier loans and defaults (what any lender's own books show)
     ledger      + earlier diversions visible on-ledger (S4/S6 routes)
     all_div     + every earlier diversion, including off-ledger collusion (S7)
                   - not observable in reality; prices what S7 hides
   Reference score: known-type probability (what a lender knowing z would use).
   Note: labels exist only for farmers who got a loan, so a model trained on
   a selective lender's book inherits its selection (reject-inference
   problem). Lending equal amounts in random order keeps this mild here.

2. Observability in the full simulation: ledger-policy gain over no-history
   as the on-ledger share of diversion goes 0 -> 0.5 -> 1.

Output: results/risk_<date>.json, results/fig_auc.png, results/fig_calibration.png
"""

import datetime as dt
import json
import os
import sys

# One thread per worker process: the pool already uses every core, and
# HistGradientBoosting's own threading on top of it oversubscribes the CPU.
os.environ.setdefault("OMP_NUM_THREADS", "1")
import warnings
from concurrent.futures import ProcessPoolExecutor
from dataclasses import replace
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import yaml
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.exceptions import ConvergenceWarning
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import brier_score_loss, roc_auc_score

from .model import Config, draw_world, known_type_prob, realise
from .policies import equal_amounts
from .run_simulation import run_replication

SEASONS = 6
REPLICATIONS = 100
FEATURE_SETS = ("land", "history", "ledger", "all_div")
SCENARIOS = {"trial_plots/custodial": ("trial_plots", "custodial"),
             "trial_plots/self_custody": ("trial_plots", "self_custody")}

SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]


def panel(cfg: Config, seed: int) -> dict:
    """Loans made under equal amounts; features are as of the start of each season."""
    w = draw_world(cfg, seed)
    order = np.random.default_rng(seed + 10**6).permutation(cfg.farmers)
    n = cfg.farmers
    loans, defaults, obs_div, all_div = (np.zeros(n) for _ in range(4))
    log_land, type_p = np.log(w.land), known_type_prob(cfg, w)
    rows = {k: [] for k in ("season", "X", "y", "type_p")}
    budget = cfg.initial_fund
    p_flat = np.full(n, cfg.default_target)
    for t in range(cfg.seasons):
        level = equal_amounts(n, p_flat, cfg.credit_levels, budget, cfg.loss_cap_share * budget, order)
        out = realise(cfg, w, t, level)
        b = level > 0
        diverted = b & (w.u_divert[t] < cfg.leakage)
        rows["season"].append(np.full(b.sum(), t))
        rows["X"].append(np.column_stack([log_land, loans, defaults, obs_div, all_div])[b])
        rows["y"].append(out.defaulted[b].astype(int))
        rows["type_p"].append(type_p[b])
        loans += b
        defaults += out.defaulted
        obs_div += out.diverted_observed
        all_div += diverted
    return {k: np.concatenate(v) for k, v in rows.items()}


COLUMNS = {"land": [0], "history": [0, 1, 2], "ledger": [0, 1, 2, 3], "all_div": [0, 1, 2, 4]}


def evaluate(data: dict) -> dict:
    """Train on seasons < t, test on season t, for t = 1..T-1 (0-based)."""
    out = {fs: {"auc": [], "brier": []} for fs in (*FEATURE_SETS, "known_type", "pooled")}
    out["calibration"] = {"pred": [], "obs": []}
    season, X, y = data["season"], data["X"], data["y"]
    for t in range(1, SEASONS):
        tr, te = season < t, season == t
        if y[tr].min() == y[tr].max() or y[te].min() == y[te].max():
            continue
        pooled = np.full(te.sum(), y[tr].mean())
        out["pooled"]["auc"].append(0.5)
        out["pooled"]["brier"].append(brier_score_loss(y[te], pooled))
        out["known_type"]["auc"].append(roc_auc_score(y[te], data["type_p"][te]))
        out["known_type"]["brier"].append(brier_score_loss(y[te], data["type_p"][te]))
        for fs in FEATURE_SETS:
            cols = COLUMNS[fs]
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", ConvergenceWarning)
                model = LogisticRegression(C=10.0, max_iter=500).fit(X[tr][:, cols], y[tr])
            p = model.predict_proba(X[te][:, cols])[:, 1]
            out[fs]["auc"].append(roc_auc_score(y[te], p))
            out[fs]["brier"].append(brier_score_loss(y[te], p))
            if fs == "ledger" and t == SEASONS - 1:
                out["calibration"]["pred"].append(p)
                out["calibration"]["obs"].append(y[te])
    return out


def gbm_check(data: dict) -> dict:
    """Does a flexible model find more in the same ledger features? (last season only)"""
    season, X, y = data["season"], data["X"], data["y"]
    tr, te = season < SEASONS - 1, season == SEASONS - 1
    cols = COLUMNS["ledger"]
    lr = LogisticRegression(C=10.0, max_iter=500).fit(X[tr][:, cols], y[tr])
    gb = HistGradientBoostingClassifier(max_iter=200, learning_rate=0.05, random_state=0).fit(X[tr][:, cols], y[tr])
    return {"logistic": roc_auc_score(y[te], lr.predict_proba(X[te][:, cols])[:, 1]),
            "boosting": roc_auc_score(y[te], gb.predict_proba(X[te][:, cols])[:, 1])}


def one_rep(args) -> tuple[dict, dict]:
    cfg, seed = args
    data = panel(cfg, seed)
    return evaluate(data), gbm_check(data)


def ci(v) -> dict:
    v = np.asarray(v, dtype=float)
    return {"mean": float(v.mean()), "ci95": float(1.96 * v.std(ddof=1) / np.sqrt(len(v)))}


def style(ax) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(INK_2)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)
    ax.grid(color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def main() -> int:
    sim = yaml.safe_load(Path("params.yaml").read_text())["simulation"]
    results = {"seasons": SEASONS, "replications": REPLICATIONS, "evaluation": {}, "observability": {}}
    by_season_plot = None
    with ProcessPoolExecutor() as pool:
        for key, (ret_name, custody) in SCENARIOS.items():
            cfg = Config.from_params(sim, ret=sim["return_scenarios"][ret_name],
                                     leakage=sim["leakage_by_custody"][custody], seasons=SEASONS)
            reps = list(pool.map(one_rep, [(cfg, s) for s in range(REPLICATIONS)], chunksize=4))
            ev = {}
            for fs in (*FEATURE_SETS, "known_type", "pooled"):
                auc = np.array([r[0][fs]["auc"] for r in reps])      # (reps, seasons-1)
                brier = np.array([r[0][fs]["brier"] for r in reps])
                ev[fs] = {"auc_by_test_season": [ci(auc[:, k]) for k in range(auc.shape[1])],
                          "auc_last": ci(auc[:, -1]), "brier_last": ci(brier[:, -1])}
            pred = np.concatenate([np.concatenate(r[0]["calibration"]["pred"]) for r in reps])
            obs = np.concatenate([np.concatenate(r[0]["calibration"]["obs"]) for r in reps])
            edges = np.quantile(pred, np.linspace(0, 1, 11))
            idx = np.clip(np.searchsorted(edges, pred, side="right") - 1, 0, 9)
            ev["calibration_last_season"] = [{"pred": float(pred[idx == b].mean()), "obs": float(obs[idx == b].mean()),
                                              "n": int((idx == b).sum())} for b in range(10)]
            ev["boosting_vs_logistic_last"] = {m: ci([r[1][m] for r in reps]) for m in ("logistic", "boosting")}
            results["evaluation"][key] = ev
            if custody == "self_custody":
                by_season_plot = (key, ev)
            print(key, {fs: round(ev[fs]["auc_last"]["mean"], 3) for fs in (*FEATURE_SETS, "known_type")},
                  "| boosting vs logistic:", {m: round(v["mean"], 3) for m, v in ev["boosting_vs_logistic_last"].items()},
                  flush=True)

        # Observability: full simulation, ledger vs no-history, as the on-ledger share of diversion varies.
        for share in (0.0, 0.5, 1.0):
            cfg = Config.from_params(sim, ret=sim["return_scenarios"]["trial_plots"],
                                     leakage=sim["leakage_by_custody"]["self_custody"],
                                     diversion_observed=share)
            reps = list(pool.map(run_replication, [(cfg, s) for s in range(sim["replications"])], chunksize=8))
            d = np.array([r["ledger"]["gain"] - r["no_history"]["gain"] for r in reps])
            base = np.mean([r["no_history"]["gain"] for r in reps])
            results["observability"][str(share)] = {"ledger_vs_no_history_pct": float(100 * d.mean() / base),
                                                    "ci95_pct": float(100 * 1.96 * d.std(ddof=1) / np.sqrt(len(d)) / base)}
            print(f"diversion on-ledger share {share}: ledger vs no history "
                  f"{results['observability'][str(share)]['ledger_vs_no_history_pct']:+.1f}% "
                  f"(±{results['observability'][str(share)]['ci95_pct']:.1f})", flush=True)

    stamp = dt.date.today().isoformat()
    Path("results", f"risk_{stamp}.json").write_text(json.dumps({"date": stamp, **results}, indent=2))

    key, ev = by_season_plot
    labels = {"land": "Land only", "history": "+ loan/default history",
              "ledger": "+ on-ledger diversion", "all_div": "+ all diversion (incl. off-ledger)"}
    fig, ax = plt.subplots(figsize=(7.2, 4.0), facecolor=SURFACE)
    style(ax)
    seasons = np.arange(2, SEASONS + 1)
    for color, fs in zip(SERIES, FEATURE_SETS):
        y = [s["mean"] for s in ev[fs]["auc_by_test_season"]]
        ax.plot(seasons, y, color=color, linewidth=2, marker="o", markersize=5,
                markeredgecolor=SURFACE, markeredgewidth=1, label=labels[fs])
    kt = [s["mean"] for s in ev["known_type"]["auc_by_test_season"]]
    ax.plot(seasons, kt, color=INK_2, linewidth=1.2, linestyle="--", label="Known type (benchmark)")
    ax.set_xticks(seasons)
    ax.set_xlabel("Test season (trained on all earlier seasons)", fontsize=9, color=INK_2)
    ax.set_ylabel("AUC, out of time", fontsize=9, color=INK_2)
    ax.legend(frameon=False, fontsize=8.5, labelcolor=INK, loc="lower right", bbox_to_anchor=(1.0, 0.1))
    fig.suptitle(f"Ledger history keeps improving the risk ranking, but stays below\nknowing the farmer ({key}, {REPLICATIONS} replications)",
                 x=0.02, ha="left", fontsize=11, color=INK)
    fig.tight_layout()
    fig.savefig(Path("results", "fig_auc.png"), dpi=200)
    plt.close(fig)

    cal = ev["calibration_last_season"]
    fig, ax = plt.subplots(figsize=(4.6, 4.4), facecolor=SURFACE)
    style(ax)
    lim = max(max(c["pred"] for c in cal), max(c["obs"] for c in cal)) * 1.08
    ax.plot([0, lim], [0, lim], color=INK_2, linewidth=1, linestyle="--")
    ax.plot([c["pred"] for c in cal], [c["obs"] for c in cal], color=SERIES[2], linewidth=2, marker="o",
            markersize=6, markeredgecolor=SURFACE, markeredgewidth=1)
    ax.text(lim * 0.03, lim * 0.93, "dashed: perfect calibration", fontsize=8.5, color=INK_2)
    ax.set_xlim(0, lim)
    ax.set_ylim(0, lim)
    ax.set_xlabel("Predicted default rate (decile mean)", fontsize=9, color=INK_2)
    ax.set_ylabel("Observed default rate", fontsize=9, color=INK_2)
    fig.suptitle(f"Ledger model calibration, season {SEASONS}\n({key})", x=0.03, ha="left", fontsize=11, color=INK)
    fig.tight_layout()
    fig.savefig(Path("results", "fig_calibration.png"), dpi=200)
    plt.close(fig)
    return 0


if __name__ == "__main__":
    sys.exit(main())
